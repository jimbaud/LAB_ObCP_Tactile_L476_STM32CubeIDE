/*
 * Décompresser les lignes visibles du logo dans une bande.
 *
 * Pour chaque ligne utile, les couples longueur-indice décrivent des segments de couleur
 * constante. Le rendu ne crée aucun tampon du logo et garde le pas de la bande Gfx.
 */
void logo_draw(Gfx *g, int x, int y)
{
    /* rows donne les bornes de chaque ligne dans runs. Deux octets codent longueur puis indice de palette. */
    for (int row = 0; row < LOGO_HEIGHT; ++row) {
        if (y + row < g->clip.y || y + row >= g->clip.y + g->clip.h) {
            continue;
        }
        int column = x;
        for (unsigned i = rows[row]; i < rows[row + 1]; i += 2U) {
            gfx_fill(g, (Rect){(int16_t)column, (int16_t)(y + row), runs[i], 1}, palette[runs[i + 1U]]);
            column += runs[i];
        }
    }
}
